def p(*xs):
    return ''.join(f'<p>{x}</p>' for x in xs)

def card(name, rows, status=None):
    head = f'<div class="v34-card-head"><b>{name}</b>　5W2H 速记卡{(" " + tag(status)) if status else ""}</div>'
    keys = [('What', '是什么'), ('Why', '为什么需要'), ('Where', '在链路哪一步'), ('When', '什么时候发生'),
            ('Who', '谁负责'), ('How', '怎么工作'), ('How much', '量化与边界')]
    body = ''.join(f'<tr><th>{k}<small>{z}</small></th><td>{rows[i]}</td></tr>' for i, (k, z) in enumerate(keys))
    return f'<div class="v34-card">{head}<table>{body}</table></div>'

def fig(key, title, how):
    return f'<!--fig:{key}|{title}--><div class="v34-howto"><div class="v34-howto-h">怎么看这张图</div>{how}</div>'

def table(headers, rows):
    h = ''.join(f'<th>{x}</th>' for x in headers)
    b = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<div class="v34-table"><table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table></div>'

def say(x):  # “讲给别人听”提示框
    return f'<div class="v34-say"><div class="v34-say-h">讲给别人听时，这样说</div>{x}</div>'

def src(*items):
    links = '<span> · </span>'.join(f'<a href="{u}" target="_blank" rel="noopener noreferrer">{E(t)}</a>' for t, u in items)
    return f'<p class="v34-src">依据：{links}</p>'

