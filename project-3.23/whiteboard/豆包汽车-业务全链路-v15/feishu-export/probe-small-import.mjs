import fs from 'node:fs';
import zlib from 'node:zlib';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from '/Users/bytedance/.npm/_npx/12f3a93219d134f5/node_modules/jsdom/lib/api.js';
const dir = path.dirname(fileURLToPath(import.meta.url));
const doc = new JSDOM(fs.readFileSync(path.join(dir, 'v15-原坐标-07.drawio'), 'utf8'), {contentType:'application/xml'}).window.document;
const graph = decodeURIComponent(zlib.inflateRawSync(Buffer.from(doc.querySelector('diagram').textContent,'base64')).toString());
const model = new JSDOM(graph, {contentType:'application/xml'}).window.document;
const cells = [...model.querySelectorAll('mxCell')];
const frame = model.querySelector('mxCell[id="import-frame-7"]');
const root = cells.find(c => c.getAttribute('parent') === frame.id && !c.id.startsWith('import-anchor'));
const wanted = new Set([root.id]);
for (const cell of cells) if(wanted.has(cell.getAttribute('parent'))) wanted.add(cell.id);
for (const id of ['0','1',frame.id,'import-anchor-7']) wanted.add(id);
for (const cell of cells) if (!wanted.has(cell.id)) cell.remove();
const count = model.querySelectorAll('mxCell').length - 4;
const data = zlib.deflateRawSync(Buffer.from(encodeURIComponent(model.documentElement.outerHTML))).toString('base64');
fs.writeFileSync(path.join(dir,'v15-小批验证.drawio'), `<mxfile><diagram name="v15" id="v15-small">${data}</diagram></mxfile>`);
console.log(JSON.stringify({originalCells:count,firstRoot:root.id}));
