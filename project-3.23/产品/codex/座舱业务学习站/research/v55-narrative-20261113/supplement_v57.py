def add(number, title, heading, anchor_start, body, sources):
    paragraph = next(p for p in original.split('\n\n') if p.startswith(anchor_start))
    assert original.count(paragraph) == 1, (number, '原稿锚点不唯一')
    assert len(re.findall(r'\*\*[^*]+\*\*', body)) == 1, (number, '每项必须恰好一句加粗')
    records.append(dict(number=number, title=title, heading=heading, anchor=paragraph,
                        body=body.strip(), sources=sources))
    result = original
    grouped = {}
    for item in records:
        grouped.setdefault(item['anchor'], []).append(item['body'])
    for anchor, bodies in grouped.items():
        result = result.replace(anchor, anchor + '\n\n' + '\n\n'.join(bodies), 1)
    DST.write_text(result)
    print('已保存补充', number, flush=True)


