 def text(self,x,y,lines,size=24,color='#1B3144',anchor='middle',weight=400):
  self.parts.append(f'<text x="{x}" y="{y}" font-size="{size}" fill="{color}" text-anchor="{anchor}" font-weight="{weight}">'+''.join(f'<tspan x="{x}" dy="{0 if i==0 else size*1.45}">{html.escape(s)}</tspan>' for i,s in enumerate(lines))+'</text>')
 def node(self,id,col,y,lines,kind='box',suggest=False,w=440):
  cx=[320,900,1480][col];hh=110 if len(lines)<3 else 145
  if kind=='diamond':hh=215
  fill='#FFF1CD' if suggest else ('#DCECF6' if col==0 else '#DCEEE3' if col==1 else '#F7E8C9')
  if kind=='diamond':
   self.parts.append(f'<rect x="-100" y="-100" width="200" height="200" fill="{fill}" stroke="#678198" stroke-width="2" transform="translate({cx},{y}) scale(1.45,0.75) rotate(45)"/>')
  else:self.parts.append(f'<rect x="{cx-w/2}" y="{y-hh/2}" width="{w}" height="{hh}" rx="12" fill="{fill}" stroke="#678198" stroke-width="2"/>')
  self.text(cx,y-(len(lines)-1)*17+8,lines,24,weight=500)
  self.nodes[id]={'cx':cx,'cy':y,'w':410 if kind=='diamond' else w,'h':hh,'kind':kind,'lines':lines,'suggest':suggest}
  for l in lines:
   width=FONT.getlength(l)
   allowed=(300 if kind=='diamond' else w-40)
   if width>allowed:self.issues.append(f'{id}: width {width:.1f} > {allowed}: {l}')
 def edge(self,a,b,label='',points=None,start='bottom',end='top',labelpos=None,dashed=False):
  A=self.nodes[a];B=self.nodes[b]
  def port(N,p):return {'top':(N['cx'],N['cy']-N['h']/2),'bottom':(N['cx'],N['cy']+N['h']/2),'left':(N['cx']-N['w']/2,N['cy']),'right':(N['cx']+N['w']/2,N['cy'])}[p]
  p1=port(A,start);p2=port(B,end)
  if points is None:
   if p1[0]==p2[0] or p1[1]==p2[1]:points=[p1,p2]
   else:points=[p1,(p1[0],(p1[1]+p2[1])/2),(p2[0],(p1[1]+p2[1])/2),p2]
  else:points=[p1]+points+[p2]
  self.edges.append({'a':a,'b':b,'label':label,'points':points})
  self.parts.append('<polyline points="'+' '.join(f'{x},{y}' for x,y in points)+'" fill="none" stroke="#42617D" stroke-width="3" marker-end="url(#arrow)"'+(' stroke-dasharray="9 7"' if dashed else '')+'/>')
  if label:
   x,y=labelpos or ((points[0][0]+points[-1][0])/2,(points[0][1]+points[-1][1])/2-12)
   width=max(64,FONT.getlength(label)+26)
   self.parts.append(f'<rect x="{x-width/2}" y="{y-25}" width="{width}" height="34" rx="5" fill="#FFFFFF"/>')
   self.text(x,y,[label],22)
 def footer(self,lines):
  self.text(70,self.h-125,lines,23,anchor='start');self.notes=lines
 def save(self):
  self.parts.append('</svg>');path=OUT/(self.name+'.svg');path.write_text('\n'.join(self.parts),encoding='utf-8')
  subprocess.run(['rsvg-convert','-o',str(OUT/(self.name+'.png')),str(path)],check=True)
  return {'file':self.name,'nodes':len(self.nodes),'decisions':sum(n['kind']=='diamond' for n in self.nodes.values()),'branches':len(self.edges),'suggested_nodes':[i for i,n in self.nodes.items() if n['suggest']],'notes':self.notes,'overflow':self.issues}
