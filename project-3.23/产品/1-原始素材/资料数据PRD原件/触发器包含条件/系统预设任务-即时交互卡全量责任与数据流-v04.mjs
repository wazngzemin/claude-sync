const out = [];
const esc = (value) => String(value)
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;');

function rect(x, y, w, h, fill = C.white, stroke = C.line, r = 14, sw = 2) {
  out.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}" fill="${fill}" stroke="${stroke}" stroke-width="${sw}"/>`);
}

function line(x1, y1, x2, y2, color = C.line, width = 2.4, arrow = true, dash = false) {
  out.push(`<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${color}" stroke-width="${width}" ${arrow ? 'marker-end="url(#arrow)"' : ''} ${dash ? 'stroke-dasharray="8 7"' : ''}/>`);
}

function poly(points, color = C.line, width = 2.4, arrow = true, dash = false) {
  out.push(`<polyline points="${points}" fill="none" stroke="${color}" stroke-width="${width}" ${arrow ? 'marker-end="url(#arrow)"' : ''} ${dash ? 'stroke-dasharray="8 7"' : ''}/>`);
}

function text(x, y, lines, size = 20, weight = 400, color = C.ink, anchor = 'start', lh = 28) {
  const spans = lines.map((t, i) => `<tspan x="${x}" dy="${i ? lh : 0}">${esc(t)}</tspan>`).join('');
  out.push(`<text x="${x}" y="${y}" font-size="${size}" font-weight="${weight}" fill="${color}" text-anchor="${anchor}">${spans}</text>`);
}

function label(x, y, value, fill = C.pale, stroke = C.blue, color = C.ink) {
  const w = Math.max(100, 28 + [...value].length * 18);
  rect(x, y, w, 40, fill, stroke, 20, 1.5);
  text(x + w / 2, y + 27, [value], 18, 650, color, 'middle');
  return w;
}

