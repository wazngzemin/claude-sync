def _t(headers, rows):
    h = ''.join(f'<th>{x}</th>' for x in headers)
    b = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<div class="v34-table"><table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table></div>'

def _p(*xs): return ''.join(f'<p>{x}</p>' for x in xs)
def _ul(*xs): return '<ul class="v36-ul">' + ''.join(f'<li>{x}</li>' for x in xs) + '</ul>'
def _h(x): return f'<div class="v38-sub">{x}</div>'

def deep(html):
    return f'<div class="v36-blk v38-deep"><div class="v36-blk-h">深一层：它为什么是现在这样</div>{html}</div>'

