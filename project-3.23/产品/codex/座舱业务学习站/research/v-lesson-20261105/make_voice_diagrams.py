class Diagram:
    def __init__(self, title, subtitle, height):
        self.parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="{height}" viewBox="0 0 1000 {height}" role="img" aria-label="{escape(title)}"><title>{escape(title)}</title><defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M1 1L9 5L1 9" fill="none" stroke="#476c8d" stroke-width="1.7"/></marker></defs><rect width="100%" height="100%" fill="#fff"/><g font-family="PingFang SC,Microsoft YaHei,Arial,sans-serif">']
        self.text(40,48,title,26,'#18364c',650)
        self.text(40,82,subtitle,17,'#5c7080')
        self.bounds=[]
    def text(self,x,y,t,size=18,color='#244358',weight=400,anchor='start'):
        self.parts.append(f'<text x="{x}" y="{y}" font-size="{size}" fill="{color}" font-weight="{weight}" text-anchor="{anchor}">{escape(t)}</text>')
    def box(self,x,y,w,h,title,lines,kind='blue'):
        palette={'blue':('#f2f7fc','#a6bfd7'),'green':('#edf8f4','#95c4b4'),'amber':('#fff8eb','#d8bf8d'),'gray':('#f5f6f7','#b7c1ca')}
        fill,stroke=palette[kind]
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="8" fill="{fill}" stroke="{stroke}"/>')
        self.text(x+18,y+32,title,20,'#203c51',600)
        for i,line in enumerate(lines): self.text(x+18,y+63+i*27,line,17)
        assert 65+max(0,len(lines)-1)*27<=h, (title,'vertical overflow')
        self.bounds.append([x,y,w,h,title])
    def path(self,points,label='',lx=0,ly=0,dash=False,both=False):
        d='M'+' L'.join(f'{x} {y}' for x,y in points)
        self.parts.append(f'<path d="{d}" fill="none" stroke="#476c8d" stroke-width="1.8" stroke-linejoin="round" marker-end="url(#arrow)"'+(' marker-start="url(#arrow)"' if both else '')+(' stroke-dasharray="6 5"' if dash else '')+'/>')
        if label:self.text(lx,ly,label,16,'#476c8d')
    def note(self,x,y,lines):
        for i,line in enumerate(lines):self.text(x,y+i*27,line,17,'#5c7080')
    def save(self,name):
        s=''.join(self.parts)+'</g></svg>'
        (OUT/f'{name}.svg').write_text(s)
        return s

