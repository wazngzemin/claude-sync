from html import escape as E

def p(*xs):
    return ''.join(f'<p>{x}</p>' for x in xs)

def ul(*xs):
    return '<ul class="v36-ul">' + ''.join(f'<li>{x}</li>' for x in xs) + '</ul>'

def blk(title, html, cls=''):
    return f'<div class="v36-blk {cls}"><div class="v36-blk-h">{title}</div>{html}</div>'

def scene(x):   return blk('用户场景', x, 'v36-scene')
def how(x):     return blk('系统怎么做', x, 'v36-how')
def pm(*xs):    return blk('产品经理要定的规则', ul(*xs), 'v36-pm')
def status(x):  return blk('现在做到哪了', x, 'v36-status')
def metric(*xs): return blk('建议关注的指标', ul(*xs), 'v36-metric')

def debug(rows):
    h = '<tr><th>用户看到的问题</th><th>可能卡在哪</th><th>该查什么</th><th>去哪看 / 找谁</th></tr>'
    b = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return blk('出了问题怎么查', f'<div class="v34-table"><table><thead>{h}</thead><tbody>{b}</tbody></table></div>', 'v36-debug')

def card(name, rows):
    keys = [('What', '是什么'), ('Why', '为什么需要'), ('Where', '在哪一步'), ('When', '什么时候'),
            ('Who', '谁负责'), ('How', '怎么做'), ('How much', '数字与边界')]
    body = ''.join(f'<tr><th>{k}<small>{z}</small></th><td>{rows[i]}</td></tr>' for i, (k, z) in enumerate(keys))
    return f'<div class="v34-card"><div class="v34-card-head"><b>{name}</b>　5W2H 速记卡</div><table>{body}</table></div>'

def fig(key, title, how_html):
    return f'<!--fig:{key}|{title}--><div class="v34-howto"><div class="v34-howto-h">怎么看这张图</div>{how_html}</div>'

def table(headers, rows):
    h = ''.join(f'<th>{x}</th>' for x in headers)
    b = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<div class="v34-table"><table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table></div>'

def say(x):
    return f'<div class="v34-say"><div class="v34-say-h">一句话讲给别人听</div>{x}</div>'

def fold(title, html):
    return f'<details class="v34-fold"><summary>{title}</summary>{html}</details>'

