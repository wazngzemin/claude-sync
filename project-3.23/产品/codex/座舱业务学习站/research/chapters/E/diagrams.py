def feedback():
    s = Svg(1260, 760, '车上回执怎样变成 DT 读到的那句话', '车控工具为例；右列是 DT 实际读到的文字（引自原文）')
    s.text(40, 104, '车上回来的', 15, '#1f4565', 650)
    s.text(380, 104, '云端怎么改写', 15, '#1d4b35', 650)
    s.text(720, 104, 'DT 读到的那句话', 15, '#6a4314', 650)
    rows = [
        ('成功，写了说明', ['例：遮阳帘开关，成功'], '原样拼成一句', ['DT 的指令 + 函数名 + 状态'], 'mem',
         ['执行指令：打开后排遮阳帘，执行结果：', '遮阳帘开关，执行成功，可简洁回复做好了｜完成。']),
        ('成功，说明为空', ['只有“成功”，没写做了什么'], '默认补一句', ['赛力斯排查指南口径'], 'warn',
         ['执行成功，可简洁回复做好了｜完成', '（这句是云端补的，不是车上写的）']),
        ('失败，带原因', ['例：靠背已到语音调节极限'], '拼上失败原因', ['原因要有对应话术（DM 逻辑）'], 'mem',
         ['……座椅靠背角度调节，执行失败，为了安全，', '已调节到语音的极限值，再调节需要用户手动操作。']),
        ('车没回结果（超时）', ['超时按几秒算，资料没写'], '按超时处理', ['统一一句；要不要重试，', '两份资料不一致，待确认'], 'mem',
         ['执行失败，请勿重复调用，需要告知用户', '']),
    ]
    for i, (t1, l1, t2, l2, k3, l3) in enumerate(rows):
        y = 120 + i * 118
        s.box(30, y, 300, 96, t1, l1, 'car', tsize=15)
        s.box(370, y, 300, 96, t2, l2, 'warn' if k3 == 'warn' else 'cloud', tsize=15)
        s.box(710, y, 520, 96, l3[0], [x for x in l3[1:] if x], k3, tsize=15)
        s.arrow([(330, y + 48), (370, y + 48)])
        s.arrow([(670, y + 48), (710, y + 48)])
    s.box(30, 610, 1200, 120, '回执只说“执行了哪个函数”，不说“车现在是什么状态”', [
        '主例：DT 下发“副驾空调温度调到4度”，回来的是“空调温度调节，执行成功，可简洁回复做好了｜完成”。',
        '车辆状态查询的返回样例里有“最低16度，最高为32度”这类范围，但没有用在执行前的校验上；车上实际调到多少度，记录里没有。'], 'warn', tsize=15)
    return s.render()


