 def __init__(self,name,title,subtitle,lanes,h):
  self.name=name;self.h=h;self.nodes={};self.edges=[];self.notes=[];self.issues=[]
  self.parts=['<svg xmlns="http://www.w3.org/2000/svg" width="1800" height="%s" viewBox="0 0 1800 %s">'%(h,h),'<defs><marker id="arrow" markerWidth="12" markerHeight="10" refX="10" refY="5" orient="auto" markerUnits="strokeWidth"><path d="M0 0 L10 5 L0 10 z" fill="#42617D"/></marker></defs>','<rect width="1800" height="%s" fill="#FFFFFF"/>'%h]
